-- Script: 04_spatial_catchment_queries.sql
-- Description: Executes native Snowflake spatial predicates (ST_CONTAINS,
--              ST_DISTANCE, ST_DWITHIN) to analyze 500m catchment visits.
-- ====================================================================

USE DATABASE GEOPULSE_DB;
USE WAREHOUSE GEOPULSE_WH;

-- 1. Spatial Join: Pings inside 500m Catchment with Metric Distance
CREATE OR REPLACE VIEW GEOPULSE_DB.GEOSPATIAL.VW_PINGS_WITHIN_500M_CATCHMENT AS
SELECT 
    p.PING_ID,
    p.DEVICE_ID,
    p.TIMESTAMP,
    p.LATITUDE AS PING_LATITUDE,
    p.LONGITUDE AS PING_LONGITUDE,
    p.SPEED_KMH,
    p.ACTIVITY_TYPE,
    p.H3_RES9,
    s.STORE_ID,
    s.STORE_NAME,
    s.CATEGORY AS STORE_CATEGORY,
    s.LATITUDE AS STORE_LATITUDE,
    s.LONGITUDE AS STORE_LONGITUDE,
    -- Exact geodesic distance in meters between device ping and store center
    ROUND(ST_DISTANCE(s.STORE_POINT_GEOG, p.LOCATION_GEOGRAPHY), 2) AS DISTANCE_TO_STORE_METERS,
    TRUE AS IN_500M_CATCHMENT
FROM GEOPULSE_DB.RAW.GPS_MOBILITY_PINGS p
INNER JOIN GEOPULSE_DB.RAW.RETAIL_STORES s
    ON ST_CONTAINS(s.CATCHMENT_500M_GEOG, p.LOCATION_GEOGRAPHY);

-- 2. Store-Level Footfall & Catchment KPI Summary
CREATE OR REPLACE TABLE GEOPULSE_DB.ANALYTICS.AGG_STORE_CATCHMENT_METRICS AS
SELECT 
    v.STORE_ID,
    v.STORE_NAME,
    v.STORE_CATEGORY,
    COUNT(v.PING_ID) AS TOTAL_CATCHMENT_PINGS,
    COUNT(DISTINCT v.DEVICE_ID) AS UNIQUE_VISITORS,
    ROUND(AVG(v.DISTANCE_TO_STORE_METERS), 2) AS AVG_DISTANCE_METERS,
    ROUND(MEDIAN(v.DISTANCE_TO_STORE_METERS), 2) AS MEDIAN_DISTANCE_METERS,
    COUNT(CASE WHEN v.ACTIVITY_TYPE = 'IN_STORE' THEN 1 END) AS IN_STORE_PINGS,
    COUNT(CASE WHEN v.ACTIVITY_TYPE = 'PEDESTRIAN' THEN 1 END) AS PEDESTRIAN_PINGS,
    ROUND(COUNT(CASE WHEN v.ACTIVITY_TYPE = 'IN_STORE' THEN 1 END) * 100.0 / NULLIF(COUNT(v.PING_ID), 0), 2) AS IN_STORE_RATIO_PCT
FROM GEOPULSE_DB.GEOSPATIAL.VW_PINGS_WITHIN_500M_CATCHMENT v
GROUP BY 1, 2, 3
ORDER BY TOTAL_CATCHMENT_PINGS DESC;

-- 3. Hourly Diurnal Foot-Traffic Distribution across Catchments
CREATE OR REPLACE VIEW GEOPULSE_DB.ANALYTICS.VW_HOURLY_CATCHMENT_TRAFFIC AS
SELECT 
    v.STORE_ID,
    v.STORE_NAME,
    DATE(v.TIMESTAMP) AS VISIT_DATE,
    HOUR(v.TIMESTAMP) AS VISIT_HOUR,
    COUNT(v.PING_ID) AS HOURLY_PINGS,
    COUNT(DISTINCT v.DEVICE_ID) AS HOURLY_UNIQUE_DEVICES
FROM GEOPULSE_DB.GEOSPATIAL.VW_PINGS_WITHIN_500M_CATCHMENT v
GROUP BY 1, 2, 3, 4
ORDER BY VISIT_DATE, VISIT_HOUR, HOURLY_PINGS DESC;
